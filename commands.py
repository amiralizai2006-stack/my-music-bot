# ============================================================
# پردازش جلو / عقب
# ============================================================

def parse_seek_command(text):

    parts = text.strip().split()

    if len(parts) != 2:
        return None

    command = parts[0]

    try:
        seconds = int(parts[1])
    except ValueError:
        return None

    if command not in ("جلو", "عقب"):
        return None

    if seconds < 1 or seconds > 100:
        return None

    if command == "جلو":
        return seconds

    return -seconds


# ============================================================
# پردازش شارژ
# ============================================================

def parse_charge_command(text):

    parts = text.strip().split()

    if len(parts) != 2:
        return None

    if parts[0] != "شارژ":
        return None

    try:
        days = int(parts[1])
    except ValueError:
        return None

    if days not in (10, 30, 60, 90, 180):
        return None

    return days


# ============================================================
# عنوان کال
# ============================================================

def parse_call_title(text):

    prefix = "عنوان کال"

    if not text.startswith(prefix):
        return None

    title = text[len(prefix):].strip()

    if not title:
        return None

    return title


